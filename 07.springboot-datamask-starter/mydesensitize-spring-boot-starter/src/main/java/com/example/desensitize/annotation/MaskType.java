package com.example.desensitize.annotation;

/**
 * ====================================================================
 * 【脱敏类型枚举 —— MaskType】
 *
 * 定义支持的脱敏类型，用于 {@link DataMask} 注解的 type 属性。
 *
 * 每种类型对应一种脱敏规则，由 {@code DataMaskSerializer} 根据
 * 该枚举值动态选择脱敏策略。
 * ====================================================================
 */
public enum MaskType {

    /**
     * 手机号脱敏
     * 规则：保留前 3 位 + 后 4 位，中间用脱敏符号填充
     * 示例：13812345678 → 138****5678
     */
    PHONE,

    /**
     * 姓名脱敏
     * 规则：保留姓（第一个字符/前两个字），其余用脱敏符号填充
     * 示例：张三 → 张*
     *       李小明 → 李**
     *       欧阳修 → 欧阳*
     */
    NAME,

    /**
     * 身份证号脱敏
     * 规则：保留前 6 位 + 后 4 位，中间用脱敏符号填充
     * 示例：110101199001011234 → 110101****1234
     */
    ID_CARD,

    /**
     * 邮箱脱敏
     * 规则：保留邮箱第一个字符 + @ 及后面部分
     * 示例：zhangsan@example.com → z******@example.com
     */
    EMAIL,

    /**
     * 地址脱敏
     * 规则：保留前 6 个字符，其余用脱敏符号填充
     * 示例：北京市朝阳区建国路88号 → 北京市朝阳区****
     */
    ADDRESS,

    /**
     * 自定义脱敏
     * 规则：保留前 retainStart 个 + 后 retainEnd 个，中间填充脱敏符号
     * 可通过 DesensitizeProperties 配置具体参数
     */
    CUSTOM
}